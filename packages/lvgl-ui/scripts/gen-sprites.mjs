// Turns scripts/sprites.mjs into src/cl_sprites.{c,h} (pre-scaled 16-colour indexed images,
// so the ESP32 just blits them) and, with --preview <file.png>, a contact sheet.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";
import { accents, bodies, builds, clashes, extras, headwear, palette, RECOLOUR_KEYS, sprites } from "./sprites.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.resolve(here, "../src");

function rgba(key) {
  if (key === ".") return [0, 0, 0, 0];
  const hex = palette[key];
  if (!hex) throw new Error(`unknown palette key '${key}'`);
  return [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16), 255];
}

function check(name, rows) {
  const w = rows[0].length;
  rows.forEach((r, i) => {
    if (r.length !== w) throw new Error(`${name} row ${i} is ${r.length} wide, expected ${w}`);
  });
  return { w, h: rows.length };
}

function scaled(rows, scale) {
  const { w, h } = check("sprite", rows);
  const W = w * scale;
  const H = h * scale;
  const px = new Uint8Array(W * H * 4);
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const [r, g, b, a] = rgba(rows[Math.floor(y / scale)][Math.floor(x / scale)]);
      const i = (y * W + x) * 4;
      px.set([r, g, b, a], i);
    }
  }
  return { W, H, px };
}

// ---------------------------------------------------------------- C output
let c = `/* Generated by scripts/gen-sprites.mjs from scripts/sprites.mjs — do not edit. */
#include "cl_sprites.h"

`;
let h = `/* Generated by scripts/gen-sprites.mjs — do not edit. */
#ifndef CL_SPRITES_H
#define CL_SPRITES_H

#include "lvgl.h"

`;
for (const { names, scales, recolour } of builds) {
  for (const name of names) {
    check(name, sprites[name]);
    for (const scale of scales) {
      const rows = sprites[name];
      const { w, h: hh } = check(name, rows);
      const W = w * scale;
      const H = hh * scale;
      const id = `cl_spr_${name}_x${scale}`;
      // LV_COLOR_FORMAT_I4: a 16-entry BGRA palette, then 4-bit indices (high nibble first).
      // Recolourable sprites keep o,b,h,s,p,q at fixed indices 1..6 so a look can patch the palette.
      const used = [...new Set(rows.join("").replace(/\./g, ""))];
      const keys = recolour ? [".", ...RECOLOUR_KEYS, ...used.filter((k) => !RECOLOUR_KEYS.includes(k))] : [".", ...used];
      if (keys.length > 16) throw new Error(`${name} uses more than 15 colours`);
      const bytes = [];
      for (let i = 0; i < 16; i++) {
        const [r, g, b, a] = i < keys.length ? rgba(keys[i]) : [0, 0, 0, 0];
        bytes.push(b, g, r, a);
      }
      const stride = Math.ceil(W / 2);
      for (let y = 0; y < H; y++) {
        const line = new Array(stride).fill(0);
        for (let x = 0; x < W; x++) {
          const idx = keys.indexOf(rows[Math.floor(y / scale)][Math.floor(x / scale)]);
          line[x >> 1] |= x % 2 === 0 ? idx << 4 : idx;
        }
        bytes.push(...line);
      }
      c += `static const uint8_t ${id}_data[] = {\n`;
      for (let i = 0; i < bytes.length; i += 24) {
        c += "    " + bytes.slice(i, i + 24).map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(",") + ",\n";
      }
      c += `};\nconst lv_image_dsc_t ${id} = {\n`;
      c += `    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_I4, .w = ${W}, .h = ${H}, .stride = ${stride} },\n`;
      c += `    .data_size = sizeof(${id}_data),\n    .data = ${id}_data,\n};\n\n`;
      h += `extern const lv_image_dsc_t ${id};\n`;
    }
  }
}
// ---------------------------------------------------------------- look tables
const hex = (c) => `0x${c.slice(1).toUpperCase()}`;
const SCALES = [2, 3, 5];
c += `/* Looks: one per session, chosen by cl_look_for(). See scripts/sprites.mjs. */\n`;
c += `const uint32_t cl_look_bodies[CL_LOOK_BODIES][4] = {\n${bodies.map((b) => `    {${b.colours.map(hex).join(", ")}}, /* ${b.name} */`).join("\n")}\n};\n`;
c += `const uint32_t cl_look_accents[CL_LOOK_ACCENTS][2] = {\n${accents.map((a) => `    {${a.colours.map(hex).join(", ")}}, /* ${a.name} */`).join("\n")}\n};\n`;
c += `const uint8_t cl_look_clashes[CL_LOOK_BODIES] = {${bodies
  .map((b) => (clashes[b.name] ?? []).reduce((m, n) => m | (1 << accents.findIndex((a) => a.name === n)), 0))
  .join(", ")}};\n`;
const table = (name, list) =>
  `const lv_image_dsc_t *const ${name}[${list.length}][3] = {\n${list
    .map((n) => `    {${SCALES.map((sc) => (n ? `&cl_spr_${n}_x${sc}` : "NULL")).join(", ")}},`)
    .join("\n")}\n};\n`;
c += table("cl_look_headwear", headwear);
c += table("cl_look_extras", extras);
h += `
/* ---- looks (recolourable sprites keep these palette indices) ---- */
#define CL_PAL_OUTLINE 1
#define CL_PAL_BODY 2
#define CL_PAL_HIGHLIGHT 3
#define CL_PAL_SHADE 4
#define CL_PAL_ACCENT 5
#define CL_PAL_ACCENT_SHADE 6
#define CL_LOOK_BODIES ${bodies.length}
#define CL_LOOK_ACCENTS ${accents.length}
#define CL_LOOK_HEADWEAR ${headwear.length}
#define CL_LOOK_EXTRAS ${extras.length}
/* [i][0] = scale 2, [1] = scale 3, [2] = scale 5 */
extern const uint32_t cl_look_bodies[CL_LOOK_BODIES][4];
extern const uint32_t cl_look_accents[CL_LOOK_ACCENTS][2];
extern const uint8_t cl_look_clashes[CL_LOOK_BODIES];
extern const lv_image_dsc_t *const cl_look_headwear[CL_LOOK_HEADWEAR][3];
extern const lv_image_dsc_t *const cl_look_extras[CL_LOOK_EXTRAS][3];
`;
h += "\n#endif /* CL_SPRITES_H */\n";
writeFileSync(path.join(srcDir, "cl_sprites.c"), c);
writeFileSync(path.join(srcDir, "cl_sprites.h"), h);
console.log("wrote src/cl_sprites.c and src/cl_sprites.h");

// ---------------------------------------------------------------- preview PNG
const previewIdx = process.argv.indexOf("--preview");
if (previewIdx > 0) {
  const file = process.argv[previewIdx + 1];
  const S = 8;
  const names = Object.keys(sprites);
  const cell = 18 * S;
  const cols = 5;
  const rowsN = Math.ceil(names.length / cols);
  const W = cols * cell;
  const H = rowsN * cell;
  const img = new Uint8Array(W * H * 4);
  for (let i = 0; i < W * H; i++) img.set([0x1b, 0x23, 0x33, 255], i * 4);
  names.forEach((name, n) => {
    const { W: w, H: hh, px } = scaled(sprites[name], S);
    const ox = (n % cols) * cell + S;
    const oy = Math.floor(n / cols) * cell + S;
    for (let y = 0; y < hh; y++)
      for (let x = 0; x < w; x++) {
        const i = (y * w + x) * 4;
        if (px[i + 3]) img.set(px.subarray(i, i + 4), ((oy + y) * W + ox + x) * 4);
      }
  });
  writeFileSync(file, png(W, H, img));
  console.log(`preview → ${file}`);
}

// --looks <file.png>: every body × headwear (accent and extra vary by column), for reviewing the art.
const looksIdx = process.argv.indexOf("--looks");
if (looksIdx > 0) {
  const S = 6;
  const cell = 18 * S;
  const W = headwear.length * 2 * cell;
  const H = bodies.length * cell;
  const img = new Uint8Array(W * H * 4);
  for (let i = 0; i < W * H; i++) img.set([0x1f, 0x2a, 0x3e, 255], i * 4);
  const hexRgb = (c) => [parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16), 255];
  bodies.forEach((body, bi) => {
    for (let col = 0; col < headwear.length * 2; col++) {
      const hw = headwear[col % headwear.length];
      const accent = accents[(bi + col) % accents.length];
      const extra = [null, "ex_glasses", null, "ex_freckles"][(bi + col) % 4];
      const map = { o: body.colours[0], b: body.colours[1], h: body.colours[2], s: body.colours[3], p: accent.colours[0], q: accent.colours[1] };
      for (const layer of ["face_idle", hw, extra].filter(Boolean)) {
        const rows = sprites[layer];
        for (let y = 0; y < 16 * S; y++)
          for (let x = 0; x < 16 * S; x++) {
            const k = rows[Math.floor(y / S)][Math.floor(x / S)];
            if (k === ".") continue;
            const px = map[k] ? hexRgb(map[k]) : rgba(k);
            img.set(px, ((bi * cell + S + y) * W + col * cell + S + x) * 4);
          }
      }
    }
  });
  writeFileSync(process.argv[looksIdx + 1], png(W, H, img));
  console.log(`looks → ${process.argv[looksIdx + 1]}`);
}

// --export <sprite> <scale> <file.png>: a single sprite, e.g. for favicons and docs.
const exportIdx = process.argv.indexOf("--export");
if (exportIdx > 0) {
  const [name, scale, file] = process.argv.slice(exportIdx + 1, exportIdx + 4);
  const { W, H, px } = scaled(sprites[name], Number(scale));
  writeFileSync(file, png(W, H, px));
  console.log(`exported ${name} ×${scale} → ${file}`);
}

function png(w, h, rgbaBuf) {
  const crcTable = Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c >>> 0;
  });
  const crc = (buf) => {
    let c = 0xffffffff;
    for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
  };
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const cr = Buffer.alloc(4);
    cr.writeUInt32BE(crc(td));
    return Buffer.concat([len, td, cr]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) Buffer.from(rgbaBuf.buffer, y * w * 4, w * 4).copy(raw, y * (w * 4 + 1) + 1);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
